function run(
  executable: string,
  arguments_: readonly string[],
  options: { cwd?: string; env?: NodeJS.ProcessEnv } = {},
) {
  return spawnSync(executable, arguments_, {
    cwd: options.cwd ?? repositoryRoot,
    env: options.env,
    encoding: "utf8",
    windowsHide: true,
  });
}

