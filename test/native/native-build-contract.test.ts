function writeFixtureFile(path: string, contents: Uint8Array | string): void {
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, contents);
}

function buildInvocationRoots(systemTemp: string): string[] {
  const buildBase = join(
    systemTemp,
    "codex-agent-tools",
    "windows-job-helper",
    "build-v1",
  );
  try {
    return readdirSync(buildBase, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => join(buildBase, entry.name))
      .sort();
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") {
      return [];
    }
    throw error;
  }
}

